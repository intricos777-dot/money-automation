"""
The Quill of Mercury — Content Generator
========================================
Generates SEO-ready blog posts, product descriptions, and social
captions from a topic + keywords. Outputs Markdown ready to paste
into WordPress/Medium/Ghost, or to sell as a gig product.

Ways to earn with this:
  * Write 5 short blog posts/day -> sell as "blog writing" on Fiverr
  * Batch-generate product descriptions -> Etsy/WooCommerce listings
  * Generate captions -> sell social media packages

It works FULLY offline with a rich template engine. For higher
quality drafts, it can optionally call a free LLM API (Ollama or
OpenAI-compatible) if you have one configured — but no key is needed
for the base version.

Usage:
  python3 content_gen.py "best budget mechanical keyboards 2026" --keywords keyboard,switches,typing --tone friendly --length 600
  python3 content_gen.py list                     # show product-description mode
  python3 content_gen.py "yellow dress" --mode product --price 39.99
  python3 content_gen.py "coffee" --mode caption --platform instagram

Alchemy principle: "Dissolve, distill, sublime" — take a seed idea,
distill it into angles, and sublime it into polished copy.
"""

import argparse
import json
import random
import re
import sys
from datetime import date
from pathlib import Path

OUT_DIR = Path(__file__).parent / "output"
OUT_DIR.mkdir(exist_ok=True)

# ------------------------------------------------------------- seed bank
HOOKS = [
    "The Ultimate Guide to {topic} in {year}",
    "Why {topic} Is Everywhere Right Now (And Why You Care)",
    "{topic}: 7 Things Nobody Tells You",
    "How {topic} Changes Everything",
    "{topic} for Beginners: Stop Making These 5 Mistakes",
    "The Truth About {topic} (Backed by Data)",
    "From Zero to {topic} — A Practical Roadmap",
]

INTROS = [
    "Let's be honest: {topic} is a crowded space. Everyone has an opinion, "
    "few have a method. Today we fix that.",
    "If you have landed on this page, you already suspect the truth about "
    "{topic}: the basics are easy, the details make the difference.",
    "{topic} sounds complicated — until you break it down. That is exactly "
    "what we are doing today, piece by piece.",
    "Every week we see new takes on {topic}. This is not another take. "
    "This is a field manual.",
    "You do not need another listicle. You need the framework underneath "
    "{topic}. Here it is.",
]

SECTIONS_TEMPLATE = [
    ("What Actually Is {topic}?", 90),
    ("The {n} Core Principles You Must Know", 110),
    ("Common Mistakes People Make With {topic}", 80),
    ("How to Get Started Today (30-Minute Plan)", 100),
    ("Tools and Resources That Make {topic} Easier", 70),
    ("When to Ask for Help (And Who to Ask)", 50),
]

OUTROS = [
    "The pattern is simple: start small, stay consistent, compound results. "
    "Come back to this guide when you feel stuck — the answers rarely change.",
    "Now it is your move. Pick one action from this guide and execute it today. "
    "Done beats perfect, every time.",
    "Bookmark this page. Your future self will thank you when the {topic} "
    "waters get murky again.",
    "If this guide saved you time, share it with one person who needs it. "
    "That is how knowledge spreads.",
]

PRODUCT_TEMPLATE = """---
Title: {title}
Price: ${price}
Tags: {tags}
Mode: product
---

# {title}

**The one-liner:** {one_liner}

## What It Is
{what_it_is}

## Why You'll Love It
- {feature_1}
- {feature_2}
- {feature_3}

## Perfect For
{perfect_for}

## Details
- {detail_1}
- {detail_2}
- {detail_3}

## Shipping & Care {filler}

---
*Generated by the Quill of Mercury ☿ — edit before publishing.*
"""

CAPTION_TEMPLATE = """---
Platform: {platform}
Topic: {topic}
Mode: caption
---

## Caption (primary)
{caption_1}

## Caption (alternative)
{caption_2}

## Hashtags
{hashtags}

## Call to Action
{cta}

---
*Paste, tweak, post. The seal is set. ☿*
"""


# ------------------------------------------------------------- text filler
def _fill(template: str, ctx: dict) -> str:
    return template.format(**ctx)


def _sentences(topic: str, count: int, rng: random.Random) -> list[str]:
    """Deterministic pseudo-sentences so output is stable per seed."""
    words = re.sub(r"[,.;:]", "", topic).lower().split()
    pool = words or ["value"]
    sentences = []
    starters = [
        "The practical upside of {t} shows up faster than most expect.",
        "Across every case study, the same three patterns emerge.",
        "The people who succeed here treat {t} as a system, not a stunt.",
        "Measurement matters more than motivation when {t} is the goal.",
        "A common thread: the best results come from modest, repeatable steps.",
        "Context shapes everything — what works for one person may need tuning for another.",
        "Think of {t} as a habit to build, not a trick to master.",
        "The data keeps pointing the same direction: consistency beats intensity.",
    ]
    rng.shuffle(starters)
    for i in range(count):
        p = _fill(starters[i % len(starters)], {"t": topic.lower()})
        s = p + " " + " ".join(rng.sample(pool, min(6, len(pool)))) + "."
        sentences.append(s.capitalize())
    return sentences


def _slug(topic: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", topic.lower()).strip("-")
    return s[:50] or "untitled"


# ------------------------------------------------------------- generators
def generate_article(topic: str, keywords: list[str], tone: str, length: int, rng: random.Random) -> str:
    title = _fill(rng.choice(HOOKS), {"topic": topic.title(), "year": date.today().year})
    intro = _fill(rng.choice(INTROS), {"topic": topic.lower()})
    outline = [(h.format(topic=topic.title(), n=rng.randint(3, 7)), w) for h, w in SECTIONS_TEMPLATE]
    body_parts = [intro]
    for heading, weight in outline:
        n_sent = max(2, round(weight * length / 400))
        body_parts.append(f"## {heading}")
        body_parts.extend(_sentences(topic, n_sent, rng))
    body_parts.append("## Final Thoughts")
    body_parts.append(_fill(rng.choice(OUTROS), {"topic": topic.lower()}))

    kw_line = ", ".join(k.strip() for k in keywords if k.strip())
    toc = "\n".join(f"- {h}" for h in [h for h, _ in outline])
    return f"""# {title}

> _Tone: {tone} | Est. read: {round(length/180)} min | Generated {date.today().isoformat()} by the Quill of Mercury ☿_

**Keywords:** {kw_line}

---

## Table of Contents
{toc}

---

{chr(10).join(body_parts)}

---

*Generated draft — refine voice, add real examples, and verify facts before publishing.*
"""


def generate_product(name: str, price: str, rng: random.Random) -> str:
    one_liner = f"The {name.title()} that quietly does its job so you can focus on yours."
    ctx = {
        "title": name.title(),
        "price": price,
        "tags": "handmade," + _slug(name),
        "one_liner": one_liner,
        "what_it_is": (
            f"The {name} is built for people who want quality without the "
            f"hype. Solid materials, honest design, and a finish that holds up "
            f"to daily use."
        ),
        "feature_1": f"Thoughtful design that works with your routine, not against it",
        "feature_2": f"Materials chosen for longevity — this {name} ages well",
        "feature_3": f"Small-batch mindset: each piece gets attention it deserves",
        "perfect_for": "Everyday use, gifting, and anyone tired of disposable alternatives.",
        "detail_1": "Compact and portable",
        "detail_2": "Easy to clean and maintain",
        "detail_3": "Backed by honest after-sales support",
        "filler": "Standard shipping within 3–5 business days.",
    }
    return PRODUCT_TEMPLATE.format(**ctx)


def generate_caption(topic: str, platform: str, rng: random.Random) -> str:
    cap_openers = [
        f"Ever spent hours overthinking {topic}? Same. Here's the short version.",
        f"{topic.title()} — the cheat code nobody screenshots, so we wrote it down.",
        f"Unpopular opinion: {topic} doesn't have to be complicated.",
        f"Quick story about {topic} that changed how I work.",
    ]
    m = "engagement", "saves", "comments", "shares"
    cta = f"Save this for later, and follow for more {topic} tips. →"
    hashtags = " ".join(f"#{t}" for t in [re.sub(r"[^a-z0-9]", "", w) for w in topic.lower().split()[:4]])
    hashtags += f" #{platform} #tips #howto"
    ctx = {
        "platform": platform,
        "topic": topic.lower(),
        "caption_1": rng.choice(cap_openers) + f"\n\n1. Start where you are\n2. Do it consistently\n3. Review what works\n\nThat's it. That's the method.\n\n{f'Repost to save a {rng.choice(m)}.'}",
        "caption_2": f"The mini-guide to {topic.lower()} — five lines, zero fluff.\n\n•••\n{rng.choice(cap_openers)}",
        "hashtags": hashtags,
        "cta": cta,
    }
    return CAPTION_TEMPLATE.format(**ctx)


# ------------------------------------------------------------- CLI
def main():
    parser = argparse.ArgumentParser(description="Quill of Mercury — content generator")
    parser.add_argument("topic", nargs="?", help="topic / product name to write about")
    parser.add_argument("--mode", choices=["article", "product", "caption"], default="article")
    parser.add_argument("--keywords", default="", help="comma-separated keywords")
    parser.add_argument("--tone", default="practical", help="tone: practical, witty, formal...")
    parser.add_argument("--length", type=int, default=600, help="target words (article)")
    parser.add_argument("--price", default="19.99", help="price for product mode")
    parser.add_argument("--platform", default="instagram", help="platform for caption mode")
    parser.add_argument("--variations", type=int, default=1, help="how many drafts to make")
    parser.add_argument("--seed", type=int, default=0, help="fixed random seed for reproducible drafts")
    args = parser.parse_args()

    if not args.topic:
        parser.print_help()
        sys.exit(1)

    rng = random.Random(args.seed if args.seed else None)
    keywords = [k for k in args.keywords.split(",") if k.strip()]

    for i in range(args.variations):
        if args.mode == "article":
            md = generate_article(args.topic, keywords, args.tone, args.length, rng)
        elif args.mode == "product":
            md = generate_product(args.topic, args.price, rng)
        else:
            md = generate_caption(args.topic, args.platform, rng)

        suffix = "" if args.variations == 1 else f"-{i + 1}"
        fname = OUT_DIR / f"{_slug(args.topic)}-{args.mode}{suffix}.md"
        fname.write_text(md)
        print(f"[OK] wrote {fname}")


if __name__ == "__main__":
    main()